"""
Adaptive Learning API routes.

Endpoints:
- GET  /api/learning/recommendations
- POST /api/learning/complete-module
- POST /api/learning/regenerate-module

Behavior:
- Recommendations are ranked and refreshed after every transaction by
  `backend/ml/learning_refresh.py`.
- Module explanations are generated by Ollama and cached per (user, module)
  with a profile fingerprint. Cached content expires after 24h or when the
  user's profile changes.
"""

